os.makedirs('icons', exist_ok=True)
def build(name, art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    im = Image.new('RGBA', (18, 18), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if PAL[ch]: im.putpixel((x + 1, y + 1), (*PAL[ch], 255))
    out = im.copy()
    for y in range(18):
        for x in range(18):
            if im.getpixel((x, y))[3] == 0 and any(0 <= x + dx < 18 and 0 <= y + dy < 18 and im.getpixel((x + dx, y + dy))[3] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out.putpixel((x, y), (*PAL['o'], 255))
    out.save(f'icons/{name}.png'); return out
sheet = Image.new('RGBA', (len(ICONS) * 80, 84), (58, 62, 104, 255))
for i, (n, a) in enumerate(ICONS.items()):
    ic = build(n, a).resize((72, 72), Image.NEAREST); sheet.alpha_composite(ic, (i * 80 + 4, 6))
sheet.save('icons-sheet.png'); print(len(ICONS))
